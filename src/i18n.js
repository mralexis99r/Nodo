export function translate(language, key, values = {}) {
  let value = key.split('.').reduce((obj, part) => obj?.[part], messages[language]) ?? key;
  if (typeof value === 'object') value = value[values.count === 1 ? 'one' : 'other'] ?? key;
  for (const [name, replacement] of Object.entries(values))
    value = value.replaceAll(`{${name}}`, replacement);
  return value;
}
